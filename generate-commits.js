function getRandomDate(start, end) {
  return new Date(start.getTime() + Math.random() * (end.getTime() - start.getTime()));
}

function formatDate(date) {
  return date.toISOString().replace('T', ' ').substring(0, 19);
}

function generateCommits() {
  const timeDiff = END_DATE.getTime() - START_DATE.getTime();
  const interval = timeDiff / TOTAL_COMMITS;
  
  for (let i = 0; i < TOTAL_COMMITS; i++) {
    const commitDate = new Date(START_DATE.getTime() + (i * interval));
    const messageIndex = i % commitMessages.length;
    const message = commitMessages[messageIndex];
    
    const env = {
      GIT_AUTHOR_DATE: formatDate(commitDate),
      GIT_COMMITTER_DATE: formatDate(commitDate),
    };
    
    try {
      execSync(`git commit --allow-empty -m "${message}"`, {
        env: { ...process.env, ...env },
        stdio: 'inherit'
      });
      console.log(`[${i + 1}/${TOTAL_COMMITS}] ${formatDate(commitDate)}: ${message}`);
    } catch (error) {
      console.error(`Error creating commit ${i + 1}:`, error.message);
    }
  }
  
  console.log('\n✓ Successfully generated', TOTAL_COMMITS, 'commits');
  console.log('✓ Commits range from', formatDate(START_DATE), 'to', formatDate(END_DATE));
}

console.log('Generating', TOTAL_COMMITS, 'backdated commits...');
console.log('Date range:', formatDate(START_DATE), 'to', formatDate(END_DATE));
console.log('');

generateCommits();
